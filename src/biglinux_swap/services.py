class ServiceState(Enum):
    """systemd service states."""

    ACTIVE = "active"
    INACTIVE = "inactive"
    FAILED = "failed"
    UNKNOWN = "unknown"


@dataclass
class ZswapStatus:
    """Zswap status information."""

    enabled: bool = False
    compressor: str = ""
    zpool: str = ""
    max_pool_percent: int = 0
    pool_size_bytes: int = 0
    stored_data_bytes: int = 0


@dataclass
class ZramStatus:
    """Zram status information."""

    enabled: bool = False
    total_size_bytes: int = 0
    used_bytes: int = 0


@dataclass
class SwapFileStatus:
    """SwapFile status information."""

    enabled: bool = False
    file_count: int = 0
    max_files: int = 32
    total_size_bytes: int = 0
    files: list[SwapFileInfo] = field(default_factory=list)


@dataclass
class SwapStatus:
    """Complete swap status information."""

    service_state: ServiceState = ServiceState.UNKNOWN
    mode: str = ""
    zswap: ZswapStatus = field(default_factory=ZswapStatus)
    zram: ZramStatus = field(default_factory=ZramStatus)
    swapfile: SwapFileStatus = field(default_factory=SwapFileStatus)


class SwapService:
    """Service for interacting with systemd-swap."""

    def get_status(self, mem_stats: MemoryStats | None = None) -> SwapStatus:
        """Get current swap status. Pass mem_stats to avoid re-reading /proc/meminfo."""
        status = SwapStatus()
        status.service_state = self._get_service_state()

        try:
            result = subprocess.run(
                ["systemd-swap", "status"],
                capture_output=True,
                text=True,
                timeout=10,
            )
            if result.returncode == 0:
                self._parse_status_output(status, result.stdout)
        except (FileNotFoundError, subprocess.TimeoutExpired, OSError) as e:
            logger.warning("systemd-swap status: %s", e)

        # Read zswap statistics from sysfs (pool/stored from mem_stats if available)
        self._read_zswap_stats(status, mem_stats)

        # Read zram + swap file info from sysfs and /proc/swaps (single read)
        self._read_zram_and_swapfile_stats(status)

        return status

    def _read_zswap_stats(
        self, status: SwapStatus, mem_stats: MemoryStats | None = None
    ) -> None:
        """Read zswap parameters from sysfs. Pool/stored bytes from mem_stats if available."""
        try:
            # Check if zswap is enabled via sysfs
            zswap_enabled_path = Path("/sys/module/zswap/parameters/enabled")
            if zswap_enabled_path.exists():
                enabled_val = zswap_enabled_path.read_text().strip()
                status.zswap.enabled = enabled_val in ("Y", "1")

            # Use pre-read meminfo values if available, else read /proc/meminfo
            if mem_stats is not None:
                status.zswap.pool_size_bytes = mem_stats.zswap_pool
                status.zswap.stored_data_bytes = mem_stats.zswap_stored
            else:
                with open(MEMINFO_PATH, encoding="utf-8") as f:
                    for line in f:
                        parts = line.split()
                        if len(parts) < 2:
                            continue
                        key = parts[0].rstrip(":")
                        value_bytes = int(parts[1]) * 1024
                        if key == "Zswap":
                            status.zswap.pool_size_bytes = value_bytes
                        elif key == "Zswapped":
                            status.zswap.stored_data_bytes = value_bytes

            # Read additional parameters from sysfs
            params_path = Path("/sys/module/zswap/parameters")
            if params_path.is_dir():
                compressor_file = params_path / "compressor"
                if compressor_file.exists():
                    status.zswap.compressor = compressor_file.read_text().strip()

                max_pool_file = params_path / "max_pool_percent"
                if max_pool_file.exists():
                    status.zswap.max_pool_percent = int(
                        max_pool_file.read_text().strip()
                    )

        except (OSError, ValueError) as e:
            logger.debug("Error reading zswap stats: %s", e)

    def _read_zram_and_swapfile_stats(self, status: SwapStatus) -> None:
        """Read zram + swap file stats from sysfs and /proc/swaps in a single pass."""
        # Read zram total capacity from sysfs
        try:
            total_zram_size = 0
            for disksize_path in glob.glob("/sys/block/zram*/disksize"):
                with open(disksize_path, encoding="utf-8") as f:
                    total_zram_size += int(f.read().strip())
            if total_zram_size > 0:
                status.zram.enabled = True
                status.zram.total_size_bytes = total_zram_size
        except (OSError, ValueError) as e:
            logger.debug("Error reading zram sysfs: %s", e)

        # Use shared parser for /proc/swaps
        entries = _parse_proc_swaps()
        zram_used = 0
        swap_files: list[SwapFileInfo] = []

        for entry in entries:
            if entry.is_zram:
                zram_used += entry.used_bytes
            elif entry.is_file:
                swap_files.append(
                    SwapFileInfo(
                        path=entry.filename,
                        size_bytes=entry.size_bytes,
                        used_bytes=entry.used_bytes,
                        is_active=True,
                        priority=entry.priority,
                    )
                )

        status.zram.used_bytes = zram_used
        status.swapfile.files = swap_files
        status.swapfile.file_count = len(swap_files)
        if swap_files:
            status.swapfile.enabled = True
            status.swapfile.total_size_bytes = sum(f.size_bytes for f in swap_files)

    def _get_service_state(self) -> ServiceState:
        """Get the state of the systemd-swap service."""
        try:
            result = subprocess.run(
                ["systemctl", "is-active", "systemd-swap"],
                capture_output=True,
                text=True,
                timeout=5,
            )
            state = result.stdout.strip().lower()
            return {
                "active": ServiceState.ACTIVE,
                "inactive": ServiceState.INACTIVE,
                "failed": ServiceState.FAILED,
            }.get(state, ServiceState.UNKNOWN)
        except (FileNotFoundError, subprocess.TimeoutExpired, OSError):
            return ServiceState.UNKNOWN

    def _parse_status_output(self, status: SwapStatus, output: str) -> None:
        """Parse the output of systemd-swap status."""
        current_section = None
        for line in output.strip().split("\n"):
            line = line.strip()
            if line.startswith("Zswap:"):
                current_section = "zswap"
                status.zswap.enabled = True
            elif line.startswith("Zram:"):
                current_section = "zram"
                status.zram.enabled = True
            elif line.lower().startswith(("swapfc:", "swapfile:")):
                current_section = "swapfile"
                status.swapfile.enabled = True

            if ":" in line and current_section == "zswap":
                key, _, value = line.partition(":")
                key = key.strip().lower().replace(" ", "_")
                value = value.strip()
                if key == "compressor":
                    status.zswap.compressor = value
                elif key == "zpool":
                    status.zswap.zpool = value
                elif key == "max_pool_percent":
                    status.zswap.max_pool_percent = int(value.rstrip("%") or 0)

    def restart_service(self) -> tuple[bool, str]:
        """Restart the systemd-swap service."""
        try:
            result = subprocess.run(
                ["systemctl", "restart", "systemd-swap"],
                capture_output=True,
                text=True,
                timeout=30,
            )
            if result.returncode == 0:
                return True, _("Service restarted")
            return False, result.stderr.strip() or _("Unknown error")
        except (FileNotFoundError, subprocess.TimeoutExpired, OSError) as e:
            return False, str(e)

    def has_any_swap_in_use(self) -> bool:
        """
        Check if there is ANY swap (files, zram, partitions) with data in use.

        More conservative check - if any swap has data, it's safer to restart
        the system than to risk freezes by stopping active swap.
        """
        entries = _parse_proc_swaps()
        if not entries:
            # If we can't read, assume swap is in use for safety
            return True
        return any(entry.used_kb > 0 for entry in entries)


