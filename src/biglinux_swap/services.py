@dataclass
class ProcSwapEntry:
    """A single entry from /proc/swaps."""

    filename: str
    swap_type: str
    size_kb: int
    used_kb: int
    priority: int

    @property
    def size_bytes(self) -> int:
        return self.size_kb * 1024

    @property
    def used_bytes(self) -> int:
        return self.used_kb * 1024

    @property
    def is_zram(self) -> bool:
        return "zram" in self.filename

    @property
    def is_file(self) -> bool:
        return self.swap_type == "file" or "loop" in self.filename


def _parse_proc_swaps() -> list[ProcSwapEntry]:
    """Parse /proc/swaps into a list of swap entries."""
    entries: list[ProcSwapEntry] = []
    try:
        content = Path("/proc/swaps").read_text(encoding="utf-8")
        for line in content.strip().split("\n")[1:]:  # Skip header
            parts = line.split()
            if len(parts) >= 5:
                entries.append(
                    ProcSwapEntry(
                        filename=parts[0],
                        swap_type=parts[1],
                        size_kb=int(parts[2]),
                        used_kb=int(parts[3]),
                        priority=int(parts[4]),
                    )
                )
    except (OSError, ValueError) as e:
        logger.debug("Error parsing /proc/swaps: %s", e)
    return entries


def _get_backing_disk_bytes(device_path: str) -> int:
    """Get actual on-disk bytes for a swap device's backing file.

    For loop devices, reads the backing file path from sysfs and uses
    st_blocks to get actual compressed bytes on disk (reflects btrfs zstd).
    """
    try:
        dev_name = device_path.rsplit("/", 1)[-1]  # "/dev/loop0" → "loop0"
        backing_path = Path(f"/sys/block/{dev_name}/loop/backing_file")
        if backing_path.exists():
            backing_file = backing_path.read_text(encoding="utf-8").strip()
            st = os.stat(backing_file)
            return st.st_blocks * 512
    except (OSError, ValueError):
        pass
    return 0


